import { create } from 'zustand';
import type { VolumeLog, SetCompletionLog } from '../types';
import { useBookStore } from './bookStore';
import { toast } from './toastStore';
import { getDb, type LetterbookDb } from '../storage/db';
import { nextStamp } from '../storage/clock';
import { notifyLogsChanged } from '../domain/sync/changeSignal';
import { seriesInfoForWork } from '../services/catalogSource';
import { decideSeriesCompletion, decideSetCompletion } from '../domain/logs/cascade';
import {
  newLogId,
  pickLogRecord,
  splitRecords,
  targetKey,
  toSetLog,
  toVolumeLog,
  type LogRecord,
  type SeriesCompletionLog,
} from '../domain/logs/records';

export type { SeriesCompletionLog } from '../domain/logs/records';

// 독서 기록은 이 브라우저의 IndexedDB(Dexie)에만 저장된다. 이 기기 = 소유자.

interface LogState {
  volumeLogs: VolumeLog[];
  setCompletionLogs: SetCompletionLog[];
  seriesCompletionLogs: SeriesCompletionLog[];
  isLoading: boolean;
  /** 기록을 한 번이라도 불러왔는지 */
  hasLoaded: boolean;
  loadLogs: () => Promise<void>;
  upsertVolumeLog: (patch: Omit<VolumeLog, 'id' | 'createdAt' | 'updatedAt' | 'watched'>) => Promise<void>;
  updateReadingProgress: (volumeId: string, currentPage: number) => Promise<void>;
  upsertSetCompletionLog: (patch: Pick<SetCompletionLog, 'editionSetId' | 'workId' | 'liked' | 'rating'>) => Promise<void>;
  upsertSeriesCompletionLog: (patch: { seriesId: string; liked: boolean; rating: number | null }) => Promise<void>;
  getVolumeLog: (volumeId: string) => VolumeLog | undefined;
  getSetCompletionLog: (editionSetId: string) => SetCompletionLog | undefined;
  getSeriesCompletionLog: (seriesId: string) => SeriesCompletionLog | undefined;
  updateLogMetadata: (id: string, patch: { rating: number | null; liked: boolean; createdAt: string }) => Promise<boolean>;
  deleteLogById: (id: string) => Promise<boolean>;
  /** 관리 화면에서 작품을 지울 때 그 작품의 기록을 모두 지운다 */
  deleteLogsByWorkId: (workId: string) => Promise<boolean>;
  /**
   * 백업 불러오기: deleteIds는 먼저 지우고(묘비를 남긴다), put은 넣거나 덮어쓴다.
   * restampIds에 든 기록(덮어쓰는 충돌)은 updatedAt을 지금 도장으로 다시 찍어 다음 동기화에서 서버의 더 새 버전에 밀리지 않게 한다.
   * 그 밖의 기록(새로 더하는 것)은 파일의 시각을 그대로 쓴다.
   */
  applyImport: (put: LogRecord[], deleteIds: string[], restampIds?: string[]) => Promise<boolean>;
  /** 백업 내보내기용 원본 기록 */
  exportRecords: () => Promise<LogRecord[]>;
}

/** 새 기록의 틀. createdAt·updatedAt은 호출한 쪽이 찍은 도장이다. */
function baseRecord(logType: LogRecord['logType'], stamp: string): LogRecord {
  const now = stamp;
  return {
    id: newLogId(),
    logType,
    volumeId: null,
    editionSetId: null,
    workId: null,
    seriesId: null,
    readingState: null,
    currentPage: null,
    liked: false,
    rating: null,
    autoGenerated: false,
    createdAt: now,
    updatedAt: now,
  };
}

const logs = () => getDb().logs;

/** 쓰기가 닿는 테이블 (기록, 묘비, 시각 도장) */
const writeTables = (db: LetterbookDb) => [db.logs, db.tombstones, db.settings];

/** 행을 지우면서 같은 트랜잭션 안에서 묘비를 남긴다. 호출한 쪽이 writeTables 트랜잭션을 열어 둔다. */
async function deleteWithTombstones(db: LetterbookDb, rows: LogRecord[], stamp: string): Promise<void> {
  if (!rows.length) return;
  await db.logs.bulkDelete(rows.map((r) => r.id));
  await db.tombstones.bulkPut(rows.map((r) => ({ id: r.id, targetKey: targetKey(r), deletedAt: stamp, supersededBy: null })));
}

type SetState = (partial: Partial<LogState>) => void;
/** 저장소에서 다시 읽어 화면 상태만 갱신한다 (isLoading은 건드리지 않는다) */
async function refresh(set: SetState): Promise<void> {
  set({ ...splitRecords(await logs().toArray()), hasLoaded: true });
}

export const useLogStore = create<LogState>((set, get) => ({
  volumeLogs: [],
  setCompletionLogs: [],
  seriesCompletionLogs: [],
  isLoading: false,
  hasLoaded: false,

  loadLogs: async () => {
    set({ isLoading: true });
    try {
      const records = await logs().toArray();
      set({ ...splitRecords(records), isLoading: false, hasLoaded: true });
    } catch (error) {
      console.error('Error loading logs:', error);
      toast('독서 기록을 불러오지 못했습니다.', 'error');
      set({ isLoading: false, hasLoaded: true });
    }
  },

  upsertVolumeLog: async (patch) => {
    const db = getDb();
    // 카탈로그 읽기는 Dexie 트랜잭션 밖에서 미리 한다
    let info: Awaited<ReturnType<typeof seriesInfoForWork>> = null;
    try {
      info = await seriesInfoForWork(patch.workId);
    } catch (error) {
      console.error('Error reading series info:', error);
    }
    const setVolumeIds = useBookStore.getState().volumes
      .filter((v) => v.editionSetId === patch.editionSetId)
      .map((v) => v.id);

    try {
      // 권 기록과 완독 연쇄(세트·시리즈)는 한 트랜잭션: 중간에 실패해도 반쯤 저장되지 않는다
      await db.transaction('rw', writeTables(db), async () => {
        const stamp = await nextStamp(db);
        const prev = await db.logs.where('volumeId').equals(patch.volumeId).and((r) => r.logType === 'volume').first();
        const record: LogRecord = {
          ...(prev ?? baseRecord('volume', stamp)),
          logType: 'volume',
          volumeId: patch.volumeId,
          editionSetId: patch.editionSetId,
          workId: patch.workId,
          seriesId: null,
          readingState: patch.readingState,
          currentPage: patch.currentPage ?? null,
          liked: patch.liked,
          rating: patch.rating,
          autoGenerated: false,
          updatedAt: stamp,
        };
        await db.logs.put(record);

        // --- set_completion 자동 생성/삭제 (readingState === 'completed' 기준) ---
        const all = await db.logs.toArray();
        const volumeLogs = all.filter((r) => r.logType === 'volume').map(toVolumeLog);
        const existingCompletion = all.find((r) => r.logType === 'set_completion' && r.editionSetId === patch.editionSetId);
        const setDecision = decideSetCompletion(setVolumeIds, volumeLogs, !!existingCompletion);
        let setCompletionChanged = false;
        if (setDecision === 'create') {
          await db.logs.put({
            ...baseRecord('set_completion', await nextStamp(db)),
            workId: patch.workId,
            editionSetId: patch.editionSetId,
            autoGenerated: true,
          });
          setCompletionChanged = true;
        } else if (setDecision === 'delete' && existingCompletion) {
          await deleteWithTombstones(db, [existingCompletion], await nextStamp(db));
          setCompletionChanged = true;
        }

        // --- series_completion 자동 생성/삭제 ---
        if (!setCompletionChanged || !info) return;
        const after = await db.logs.toArray();
        const existingSeriesLog = after.find((r) => r.logType === 'series_completion' && r.seriesId === info.seriesId);
        const decision = decideSeriesCompletion(
          info.workIds,
          after.filter((r) => r.logType === 'set_completion').map(toSetLog),
          !!existingSeriesLog,
        );
        if (decision === 'create') {
          await db.logs.put({ ...baseRecord('series_completion', await nextStamp(db)), seriesId: info.seriesId, autoGenerated: true });
        } else if (decision === 'delete' && existingSeriesLog) {
          await deleteWithTombstones(db, [existingSeriesLog], await nextStamp(db));
        }
      });
    } catch (error) {
      console.error('Error upserting volume log:', error);
      toast('읽기 상태를 저장하지 못했습니다.', 'error');
      return;
    }
    await refresh(set);
    notifyLogsChanged();
  },

  updateReadingProgress: async (volumeId, currentPage) => {
    const db = getDb();
    try {
      await db.transaction('rw', writeTables(db), async () => {
        const existing = await db.logs.where('volumeId').equals(volumeId).and((r) => r.logType === 'volume').first();
        if (!existing) throw new Error('기록이 저장소에 없습니다.');
        await db.logs.update(existing.id, { currentPage, updatedAt: await nextStamp(db) });
      });
    } catch (error) {
      console.error('Error updating reading progress:', error);
      // 기록이 없으면 아무 일도 하지 않던 기존 동작을 지킨다
      if (get().volumeLogs.some((l) => l.volumeId === volumeId)) toast('쪽수를 저장하지 못했습니다.', 'error');
      return;
    }
    await refresh(set);
    notifyLogsChanged();
  },

  upsertSetCompletionLog: async (patch) => {
    const db = getDb();
    try {
      const done = await db.transaction('rw', writeTables(db), async () => {
        const existing = await db.logs
          .where('editionSetId').equals(patch.editionSetId)
          .and((r) => r.logType === 'set_completion')
          .first();
        if (!existing) return false;
        await db.logs.update(existing.id, {
          workId: patch.workId,
          liked: patch.liked,
          rating: patch.rating,
          updatedAt: await nextStamp(db),
        });
        return true;
      });
      if (!done) return;
    } catch (error) {
      console.error('Error upserting set_completion log:', error);
      toast('별점을 저장하지 못했습니다.', 'error');
      return;
    }
    await refresh(set);
    notifyLogsChanged();
  },

  upsertSeriesCompletionLog: async (patch) => {
    const db = getDb();
    try {
      await db.transaction('rw', writeTables(db), async () => {
        const stamp = await nextStamp(db);
        const prev = await db.logs.where('seriesId').equals(patch.seriesId).and((r) => r.logType === 'series_completion').first();
        const record: LogRecord = {
          ...(prev ?? baseRecord('series_completion', stamp)),
          seriesId: patch.seriesId,
          liked: patch.liked,
          rating: patch.rating,
          autoGenerated: prev ? prev.autoGenerated : false,
          updatedAt: stamp,
        };
        await db.logs.put(record);
      });
    } catch (error) {
      console.error('Error upserting series log:', error);
      toast('시리즈 평가를 저장하지 못했습니다.', 'error');
      return;
    }
    await refresh(set);
    notifyLogsChanged();
  },

  updateLogMetadata: async (id, patch) => {
    const db = getDb();
    try {
      const changed = await db.transaction('rw', writeTables(db), async () =>
        db.logs.update(id, {
          rating: patch.rating,
          liked: patch.liked,
          createdAt: patch.createdAt,
          updatedAt: await nextStamp(db),
        }),
      );
      if (!changed) return false;
    } catch (error) {
      console.error('Error updating log metadata:', error);
      return false;
    }
    await get().loadLogs();
    notifyLogsChanged();
    return true;
  },

  deleteLogById: async (id) => {
    const db = getDb();
    try {
      // 위에 걸린 완독 기록도 함께 지운다: 권 → 세트 완독 → 시리즈 완독, 세트 완독 → 시리즈 완독
      const target = await db.logs.get(id);
      const info = target?.workId ? await seriesInfoForWork(target.workId) : null;
      await db.transaction('rw', writeTables(db), async () => {
        const stamp = await nextStamp(db);
        const doomed: LogRecord[] = [];
        if (target) doomed.push(target);
        if (target?.logType === 'volume' && target.editionSetId) {
          doomed.push(...(await db.logs
            .where('editionSetId').equals(target.editionSetId)
            .and((r) => r.logType === 'set_completion')
            .toArray()));
        }
        if (info) {
          doomed.push(...(await db.logs
            .where('seriesId').equals(info.seriesId)
            .and((r) => r.logType === 'series_completion')
            .toArray()));
        }
        // 같은 행이 두 번 들어가지 않게
        await deleteWithTombstones(db, [...new Map(doomed.map((r) => [r.id, r])).values()], stamp);
      });
    } catch (error) {
      console.error('Error deleting log:', error);
      return false;
    }

    await get().loadLogs();
    notifyLogsChanged();
    return true;
  },

  deleteLogsByWorkId: async (workId) => {
    const db = getDb();
    try {
      await db.transaction('rw', writeTables(db), async () => {
        const rows = await db.logs.where('workId').equals(workId).toArray();
        await deleteWithTombstones(db, rows, await nextStamp(db));
      });
    } catch (error) {
      console.error('Error deleting logs for work:', error);
      return false;
    }
    await get().loadLogs();
    notifyLogsChanged();
    return true;
  },

  applyImport: async (put, deleteIds, restampIds = []) => {
    try {
      const db = getDb();
      const restamp = new Set(restampIds);
      await db.transaction('rw', writeTables(db), async () => {
        const stamp = await nextStamp(db);
        if (deleteIds.length) {
          const rows = (await db.logs.bulkGet(deleteIds)).filter((r): r is LogRecord => !!r);
          await deleteWithTombstones(db, rows, stamp);
        }
        // 덮어쓰는 충돌은 지금 도장으로 다시 찍는다. 새로 더하는 기록은 파일의 시각 그대로.
        if (put.length) {
          await db.logs.bulkPut(put.map((r) => (restamp.has(r.id) ? { ...pickLogRecord(r), updatedAt: stamp } : pickLogRecord(r))));
        }
      });
    } catch (error) {
      console.error('Error importing logs:', error);
      return false;
    }
    await get().loadLogs();
    notifyLogsChanged();
    return true;
  },

  exportRecords: () => logs().toArray(),

  getVolumeLog: (volumeId) => get().volumeLogs.find((l) => l.volumeId === volumeId),
  getSetCompletionLog: (editionSetId) => get().setCompletionLogs.find((l) => l.editionSetId === editionSetId),
  getSeriesCompletionLog: (seriesId) => get().seriesCompletionLogs.find((l) => l.seriesId === seriesId),
}));
