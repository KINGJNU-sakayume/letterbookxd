import { create } from 'zustand';
import type { VolumeLog, SetCompletionLog } from '../types';
import { useBookStore } from './bookStore';
import { toast } from './toastStore';
import { getDb } from '../storage/db';
import { seriesInfoForWork } from '../services/catalogSource';
import { decideSeriesCompletion, decideSetCompletion } from '../domain/logs/cascade';
import {
  newLogId,
  pickLogRecord,
  splitRecords,
  toSeriesLog,
  toSetLog,
  toVolumeLog,
  type LogRecord,
  type SeriesCompletionLog,
} from '../domain/logs/records';

export type { SeriesCompletionLog } from '../domain/logs/records';

// 독서 기록은 이 브라우저의 IndexedDB(Dexie)에만 저장된다. 이 기기 = 소유자.
// 공개 API(이름·인자·반환)는 Supabase 시절과 같다.

interface LogState {
  volumeLogs: VolumeLog[];
  setCompletionLogs: SetCompletionLog[];
  seriesCompletionLogs: SeriesCompletionLog[];
  isLoading: boolean;
  /** 기록을 한 번이라도 불러왔는지 */
  hasLoaded: boolean;
  loadLogs: () => Promise<void>;
  upsertVolumeLog: (patch: Omit<VolumeLog, 'id' | 'createdAt' | 'updatedAt' | 'watched'>) => Promise<void>;
  updateReadingProgress: (volumeId: string, currentPage: number) => Promise<void>;
  upsertSetCompletionLog: (patch: Pick<SetCompletionLog, 'editionSetId' | 'workId' | 'liked' | 'rating'>) => Promise<void>;
  upsertSeriesCompletionLog: (patch: { seriesId: string; liked: boolean; rating: number | null }) => Promise<void>;
  getVolumeLog: (volumeId: string) => VolumeLog | undefined;
  getSetCompletionLog: (editionSetId: string) => SetCompletionLog | undefined;
  getSeriesCompletionLog: (seriesId: string) => SeriesCompletionLog | undefined;
  updateLogMetadata: (id: string, patch: { rating: number | null; liked: boolean; createdAt: string }) => Promise<boolean>;
  deleteLogById: (id: string) => Promise<boolean>;
  /** 관리 화면에서 작품을 지울 때 그 작품의 기록을 모두 지운다 */
  deleteLogsByWorkId: (workId: string) => Promise<boolean>;
  /** 백업 불러오기: put은 넣거나 덮어쓰고, deleteIds는 먼저 지운다 */
  applyImport: (put: LogRecord[], deleteIds: string[]) => Promise<boolean>;
  /** 백업 내보내기용 원본 기록 */
  exportRecords: () => Promise<LogRecord[]>;
}

const nowIso = () => new Date().toISOString();

function baseRecord(logType: LogRecord['logType']): LogRecord {
  const now = nowIso();
  return {
    id: newLogId(),
    logType,
    volumeId: null,
    editionSetId: null,
    workId: null,
    seriesId: null,
    readingState: null,
    currentPage: null,
    liked: false,
    rating: null,
    autoGenerated: false,
    createdAt: now,
    updatedAt: now,
  };
}

const logs = () => getDb().logs;

export const useLogStore = create<LogState>((set, get) => ({
  volumeLogs: [],
  setCompletionLogs: [],
  seriesCompletionLogs: [],
  isLoading: false,
  hasLoaded: false,

  loadLogs: async () => {
    set({ isLoading: true });
    try {
      const records = await logs().toArray();
      set({ ...splitRecords(records), isLoading: false, hasLoaded: true });
    } catch (error) {
      console.error('Error loading logs:', error);
      toast('독서 기록을 불러오지 못했습니다.', 'error');
      set({ isLoading: false, hasLoaded: true });
    }
  },

  upsertVolumeLog: async (patch) => {
    const state = get();
    const existing = state.volumeLogs.find((cl) => cl.volumeId === patch.volumeId);

    const prev = existing ? await logs().get(existing.id) : undefined;
    const record: LogRecord = {
      ...(prev ?? baseRecord('volume')),
      logType: 'volume',
      volumeId: patch.volumeId,
      editionSetId: patch.editionSetId,
      workId: patch.workId,
      seriesId: null,
      readingState: patch.readingState,
      currentPage: patch.currentPage ?? null,
      liked: patch.liked,
      rating: patch.rating,
      autoGenerated: false,
      updatedAt: nowIso(),
    };
    if (!prev && existing) {
      record.id = existing.id;
      record.createdAt = existing.createdAt;
    }

    try {
      await logs().put(record);
    } catch (error) {
      console.error('Error upserting volume log:', error);
      toast('읽기 상태를 저장하지 못했습니다.', 'error');
      return;
    }

    const saved = toVolumeLog(record);
    const updatedVolumeLogs = existing
      ? state.volumeLogs.map((cl) => (cl.volumeId === patch.volumeId ? saved : cl))
      : [...state.volumeLogs, saved];
    set({ volumeLogs: updatedVolumeLogs });

    // --- set_completion 자동 생성/삭제 (readingState === 'completed' 기준) ---
    const setVolumeIds = useBookStore.getState().volumes
      .filter((v) => v.editionSetId === patch.editionSetId)
      .map((v) => v.id);
    const existingCompletion = get().setCompletionLogs.find((l) => l.editionSetId === patch.editionSetId);
    const setDecision = decideSetCompletion(setVolumeIds, updatedVolumeLogs, !!existingCompletion);
    let setCompletionChanged = false;

    try {
      if (setDecision === 'create') {
        const completion: LogRecord = {
          ...baseRecord('set_completion'),
          workId: patch.workId,
          editionSetId: patch.editionSetId,
          autoGenerated: true,
        };
        await logs().put(completion);
        set((s) => ({ setCompletionLogs: [...s.setCompletionLogs, toSetLog(completion)] }));
        setCompletionChanged = true;
      } else if (setDecision === 'delete' && existingCompletion) {
        await logs().delete(existingCompletion.id);
        set((s) => ({ setCompletionLogs: s.setCompletionLogs.filter((cl) => cl.editionSetId !== patch.editionSetId) }));
        setCompletionChanged = true;
      }
    } catch (error) {
      console.error('Error updating set_completion log:', error);
    }

    // --- series_completion 자동 생성/삭제 ---
    if (!setCompletionChanged) return;
    try {
      const info = await seriesInfoForWork(patch.workId);
      if (!info) return;
      const existingSeriesLog = get().seriesCompletionLogs.find((l) => l.seriesId === info.seriesId);
      const decision = decideSeriesCompletion(info.workIds, get().setCompletionLogs, !!existingSeriesLog);
      if (decision === 'create') {
        const seriesLog: LogRecord = { ...baseRecord('series_completion'), seriesId: info.seriesId, autoGenerated: true };
        await logs().put(seriesLog);
        set((s) => ({ seriesCompletionLogs: [...s.seriesCompletionLogs, toSeriesLog(seriesLog)] }));
      } else if (decision === 'delete' && existingSeriesLog) {
        await logs().delete(existingSeriesLog.id);
        set((s) => ({ seriesCompletionLogs: s.seriesCompletionLogs.filter((l) => l.seriesId !== info.seriesId) }));
      }
    } catch (error) {
      console.error('Error updating series_completion log:', error);
    }
  },

  updateReadingProgress: async (volumeId, currentPage) => {
    const existing = get().volumeLogs.find((l) => l.volumeId === volumeId);
    if (!existing) return;
    try {
      const updatedAt = nowIso();
      const changed = await logs().update(existing.id, { currentPage, updatedAt });
      if (!changed) throw new Error('기록이 저장소에 없습니다.');
      set((s) => ({
        volumeLogs: s.volumeLogs.map((l) => (l.volumeId === volumeId ? { ...l, currentPage, updatedAt } : l)),
      }));
    } catch (error) {
      console.error('Error updating reading progress:', error);
      toast('쪽수를 저장하지 못했습니다.', 'error');
    }
  },

  upsertSetCompletionLog: async (patch) => {
    const state = get();
    const existing = state.setCompletionLogs.find((cl) => cl.editionSetId === patch.editionSetId);
    if (!existing) return;

    const updated: SetCompletionLog = { ...existing, liked: patch.liked, rating: patch.rating };
    set({ setCompletionLogs: state.setCompletionLogs.map((cl) => (cl.editionSetId === patch.editionSetId ? updated : cl)) });

    try {
      const changed = await logs().update(existing.id, {
        workId: patch.workId,
        liked: patch.liked,
        rating: patch.rating,
        updatedAt: nowIso(),
      });
      if (!changed) throw new Error('기록이 저장소에 없습니다.');
    } catch (error) {
      console.error('Error upserting set_completion log:', error);
      toast('별점을 저장하지 못했습니다.', 'error');
      set((s) => ({ setCompletionLogs: s.setCompletionLogs.map((cl) => (cl.id === existing.id ? existing : cl)) }));
    }
  },

  upsertSeriesCompletionLog: async (patch) => {
    const existing = get().seriesCompletionLogs.find((cl) => cl.seriesId === patch.seriesId);
    const prev = existing ? await logs().get(existing.id) : undefined;
    const record: LogRecord = {
      ...(prev ?? baseRecord('series_completion')),
      seriesId: patch.seriesId,
      liked: patch.liked,
      rating: patch.rating,
      autoGenerated: existing ? existing.autoGenerated : false,
      updatedAt: nowIso(),
    };
    if (!prev && existing) {
      record.id = existing.id;
      record.createdAt = existing.createdAt;
    }

    try {
      await logs().put(record);
    } catch (error) {
      console.error('Error upserting series log:', error);
      toast('시리즈 평가를 저장하지 못했습니다.', 'error');
      return;
    }

    const updatedLog = toSeriesLog(record);
    set((s) => ({
      seriesCompletionLogs: existing
        ? s.seriesCompletionLogs.map((cl) => (cl.seriesId === patch.seriesId ? updatedLog : cl))
        : [...s.seriesCompletionLogs, updatedLog],
    }));
  },

  updateLogMetadata: async (id, patch) => {
    try {
      const changed = await logs().update(id, {
        rating: patch.rating,
        liked: patch.liked,
        createdAt: patch.createdAt,
        updatedAt: nowIso(),
      });
      if (!changed) return false;
    } catch (error) {
      console.error('Error updating log metadata:', error);
      return false;
    }
    await get().loadLogs();
    return true;
  },

  deleteLogById: async (id) => {
    const state = get();
    const volumeLog = state.volumeLogs.find((l) => l.id === id);
    const setLog = state.setCompletionLogs.find((l) => l.id === id);

    try {
      // 위에 걸린 완독 기록도 함께 지운다: 권 → 세트 완독 → 시리즈 완독, 세트 완독 → 시리즈 완독
      const workId = volumeLog?.workId ?? setLog?.workId;
      const info = workId ? await seriesInfoForWork(workId) : null;
      const db = getDb();
      await db.transaction('rw', db.logs, async () => {
        await db.logs.delete(id);
        if (volumeLog) {
          await db.logs
            .where('editionSetId').equals(volumeLog.editionSetId)
            .and((r) => r.logType === 'set_completion')
            .delete();
        }
        if (info) {
          await db.logs
            .where('seriesId').equals(info.seriesId)
            .and((r) => r.logType === 'series_completion')
            .delete();
        }
      });
    } catch (error) {
      console.error('Error deleting log:', error);
      return false;
    }

    await get().loadLogs();
    return true;
  },

  deleteLogsByWorkId: async (workId) => {
    try {
      await logs().where('workId').equals(workId).delete();
    } catch (error) {
      console.error('Error deleting logs for work:', error);
      return false;
    }
    await get().loadLogs();
    return true;
  },

  applyImport: async (put, deleteIds) => {
    try {
      const db = getDb();
      await db.transaction('rw', db.logs, async () => {
        if (deleteIds.length) await db.logs.bulkDelete(deleteIds);
        if (put.length) await db.logs.bulkPut(put.map(pickLogRecord));
      });
    } catch (error) {
      console.error('Error importing logs:', error);
      return false;
    }
    await get().loadLogs();
    return true;
  },

  exportRecords: () => logs().toArray(),

  getVolumeLog: (volumeId) => get().volumeLogs.find((l) => l.volumeId === volumeId),
  getSetCompletionLog: (editionSetId) => get().setCompletionLogs.find((l) => l.editionSetId === editionSetId),
  getSeriesCompletionLog: (seriesId) => get().seriesCompletionLogs.find((l) => l.seriesId === seriesId),
}));
