import type { SetCompletionLog, VolumeLog } from '../../types';

/** 이 기기에 저장되는 기록 한 건 (IndexedDB logs 테이블, 백업 파일) */
export interface LogRecord {
  /** crypto.randomUUID(). Life Hub 영수증 entity_id로도 쓰인다. */
  id: string;
  logType: 'volume' | 'set_completion' | 'series_completion';
  volumeId: string | null;
  editionSetId: string | null;
  workId: string | null;
  seriesId: string | null;
  /** volume 기록만 의미가 있다 */
  readingState: 'unread' | 'reading' | 'completed' | null;
  currentPage: number | null;
  liked: boolean;
  rating: number | null;
  autoGenerated: boolean;
  /** 처음 만든 시각. 완독 기록에서는 완독일이다. */
  createdAt: string;
  updatedAt: string;
}

export interface SeriesCompletionLog {
  id: string;
  seriesId: string;
  logType: 'series_completion';
  liked: boolean;
  rating: number | null;
  autoGenerated: boolean;
  createdAt: string;
  updatedAt: string;
}

export const LOG_ID_PATTERN = /^[A-Za-z0-9_-]{1,128}$/;

export function newLogId(): string {
  return crypto.randomUUID();
}

export function toVolumeLog(r: LogRecord): VolumeLog {
  const readingState = r.readingState ?? 'unread';
  return {
    id: r.id,
    volumeId: r.volumeId ?? '',
    editionSetId: r.editionSetId ?? '',
    workId: r.workId ?? '',
    logType: 'volume',
    watched: readingState === 'completed',
    readingState,
    currentPage: r.currentPage,
    liked: r.liked,
    rating: r.rating,
    createdAt: r.createdAt,
    updatedAt: r.updatedAt,
  };
}

export function toSetLog(r: LogRecord): SetCompletionLog {
  return {
    id: r.id,
    editionSetId: r.editionSetId ?? '',
    workId: r.workId ?? '',
    logType: 'set_completion',
    autoGenerated: r.autoGenerated,
    liked: r.liked,
    rating: r.rating,
    createdAt: r.createdAt,
  };
}

export function toSeriesLog(r: LogRecord): SeriesCompletionLog {
  return {
    id: r.id,
    seriesId: r.seriesId ?? '',
    logType: 'series_completion',
    liked: r.liked,
    rating: r.rating,
    autoGenerated: r.autoGenerated,
    createdAt: r.createdAt,
    updatedAt: r.updatedAt,
  };
}

export function splitRecords(records: LogRecord[]) {
  return {
    volumeLogs: records.filter((r) => r.logType === 'volume').map(toVolumeLog),
    setCompletionLogs: records.filter((r) => r.logType === 'set_completion').map(toSetLog),
    seriesCompletionLogs: records.filter((r) => r.logType === 'series_completion').map(toSeriesLog),
  };
}

/** 같은 대상(권·세트·시리즈)을 가리키는 기록인지 판단하는 열쇠 */
export function targetKey(r: Pick<LogRecord, 'logType' | 'volumeId' | 'editionSetId' | 'seriesId'>): string {
  if (r.logType === 'volume') return `volume:${r.volumeId}`;
  if (r.logType === 'set_completion') return `set:${r.editionSetId}`;
  return `series:${r.seriesId}`;
}

const isIsoDate = (v: unknown): v is string => typeof v === 'string' && !Number.isNaN(Date.parse(v));
const isNullableString = (v: unknown) => v === null || typeof v === 'string';

/** 백업 등 바깥에서 들어온 값을 검사한다. 문제가 있으면 이유를, 없으면 null을 돌려준다. */
export function validateLogRecord(v: unknown): string | null {
  if (!v || typeof v !== 'object') return '기록이 객체가 아닙니다';
  const r = v as Record<string, unknown>;
  if (typeof r.id !== 'string' || !LOG_ID_PATTERN.test(r.id)) return 'id 형식이 잘못되었습니다';
  if (r.logType !== 'volume' && r.logType !== 'set_completion' && r.logType !== 'series_completion') return 'logType이 잘못되었습니다';
  for (const k of ['volumeId', 'editionSetId', 'workId', 'seriesId'] as const) {
    if (!isNullableString(r[k])) return `${k} 형식이 잘못되었습니다`;
  }
  if (r.logType === 'volume') {
    if (!r.volumeId || !r.editionSetId || !r.workId) return '권 기록에 volumeId·editionSetId·workId가 필요합니다';
    if (r.readingState !== 'unread' && r.readingState !== 'reading' && r.readingState !== 'completed') return 'readingState가 잘못되었습니다';
  }
  if (r.logType === 'set_completion' && (!r.editionSetId || !r.workId)) return '세트 완독 기록에 editionSetId·workId가 필요합니다';
  if (r.logType === 'series_completion' && !r.seriesId) return '시리즈 완독 기록에 seriesId가 필요합니다';
  if (r.currentPage !== null && !(typeof r.currentPage === 'number' && Number.isFinite(r.currentPage))) return 'currentPage 형식이 잘못되었습니다';
  if (r.rating !== null && !(typeof r.rating === 'number' && r.rating >= 0 && r.rating <= 5)) return 'rating 형식이 잘못되었습니다';
  if (typeof r.liked !== 'boolean' || typeof r.autoGenerated !== 'boolean') return 'liked·autoGenerated 형식이 잘못되었습니다';
  if (!isIsoDate(r.createdAt) || !isIsoDate(r.updatedAt)) return '날짜 형식이 잘못되었습니다';
  return null;
}

/** 저장 전에 알 수 없는 필드를 떨어낸다 */
export function pickLogRecord(r: LogRecord): LogRecord {
  return {
    id: r.id,
    logType: r.logType,
    volumeId: r.volumeId ?? null,
    editionSetId: r.editionSetId ?? null,
    workId: r.workId ?? null,
    seriesId: r.seriesId ?? null,
    readingState: r.logType === 'volume' ? r.readingState ?? 'unread' : null,
    currentPage: r.currentPage ?? null,
    liked: r.liked,
    rating: r.rating ?? null,
    autoGenerated: r.autoGenerated,
    createdAt: r.createdAt,
    updatedAt: r.updatedAt,
  };
}
