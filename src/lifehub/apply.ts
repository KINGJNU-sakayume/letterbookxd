import { useLogStore } from '../store/logStore';
import type { CatalogEdition, CatalogWork } from '../store/catalogStore';
import { ensureWorkLoaded } from '../services/bookCache';
import { createEditionSetRef, createVolumeRef } from '../domain/books/identity';
import { dayToIso } from './resolve';
import { browserDeps, rememberReceipt } from './remote';

export interface RecordForm { state: 'reading' | 'completed'; page: number | null; rating: number | null; liked: boolean; date: string | null }

/**
 * Records one approved proposal on a volume through the log store (the same completion cascade as the UI) and
 * keeps the receipt for Life Hub. Used by the review dialog and by auto-apply of Claude-card approvals.
 * Returns false when the store refused (it already showed the error).
 */
export async function recordProposal(key: string, work: CatalogWork, publisher: string, edition: CatalogEdition, form: RecordForm): Promise<boolean> {
  await ensureWorkLoaded(work.id);
  const volumeId = createVolumeRef(edition.id);
  const editionSetId = createEditionSetRef(work.id, publisher);
  const store = useLogStore.getState();
  const before = store.getVolumeLog(volumeId);
  const setBefore = store.setCompletionLogs.find((l) => l.editionSetId === editionSetId)?.id;
  await store.upsertVolumeLog({
    volumeId, editionSetId, workId: work.id, logType: 'volume',
    readingState: form.state,
    currentPage: form.state === 'reading' ? form.page ?? before?.currentPage ?? null : before?.currentPage ?? null,
    liked: form.state === 'completed' ? form.liked || (before?.liked ?? false) : before?.liked ?? false,
    rating: form.state === 'completed' ? form.rating ?? before?.rating ?? null : before?.rating ?? null,
  });
  const saved = useLogStore.getState().getVolumeLog(volumeId);
  if (!saved || saved.readingState !== form.state) return false;
  if (form.state === 'completed' && form.date) {
    const createdAt = dayToIso(form.date);
    await useLogStore.getState().updateLogMetadata(saved.id, { rating: saved.rating, liked: saved.liked, createdAt });
    // Finishing the last volume just completed the edition set: that completion (what the bookshelf and the
    // yearly count show) is dated the day the book was finished too, not today.
    const set = useLogStore.getState().setCompletionLogs.find((l) => l.editionSetId === editionSetId);
    if (set && set.id !== setBefore && set.autoGenerated) {
      await useLogStore.getState().updateLogMetadata(set.id, { rating: set.rating, liked: set.liked, createdAt });
    }
  }
  rememberReceipt(key, saved.id, browserDeps());
  return true;
}
