import './setup.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mergeLogState, mergeStates, canonicalJson, sameState, pruneTombstones, computeStamp, TOMBSTONE_KEEP_MS } from '../.test-dist/app.js';

// Synthetic data only.
const iso = (n) => new Date(Date.UTC(2026, 0, 1) + n * 1000).toISOString();
const vol = (id, volumeId, t, extra = {}) => ({
  id, logType: 'volume', volumeId, editionSetId: 'set1', workId: 'w1', seriesId: null, readingState: 'reading',
  currentPage: null, liked: false, rating: null, autoGenerated: false, createdAt: iso(0), updatedAt: iso(t), ...extra,
});
const tomb = (id, target, t, supersededBy = null) => ({ id, targetKey: target, deletedAt: iso(t), supersededBy });
const state = (logs = [], tombstones = []) => ({ logs, tombstones });
const live = (m) => m.logs.map((r) => r.id);
const dead = (m) => Object.fromEntries(m.tombstones.map((t) => [t.id, t.supersededBy]));

test('두 기기가 오프라인에서 같은 권을 기록하면 더 늦은 쪽만 남고 다른 쪽은 supersededBy 묘비', () => {
  const a = state([vol('A', 'v1', 10)]);
  const b = state([vol('B', 'v1', 20, { currentPage: 5 })]);
  const m = mergeLogState(a, b);
  assert.deepEqual(live(m), ['B']);
  assert.deepEqual(dead(m), { A: 'B' });
  assert.equal(m.tombstones[0].deletedAt, iso(20));
  assert.deepEqual(m, mergeLogState(b, a));
});

test('한 기기에서 삭제하면 다른 기기의 더 오래된 같은 권 기록도 사라진다', () => {
  const a = state([], [tomb('A', 'volume:v1', 30)]);
  const b = state([vol('B', 'v1', 20)]);
  const m = mergeLogState(a, b);
  assert.deepEqual(live(m), []);
  assert.deepEqual(dead(m), { A: null, B: null });
});

test('삭제 뒤 더 늦게 다시 기록하면 되살아난다', () => {
  const m = mergeLogState(state([], [tomb('A', 'volume:v1', 30)]), state([vol('C', 'v1', 40)]));
  assert.deepEqual(live(m), ['C']);
  assert.deepEqual(dead(m), { A: 'C' });
});

test('기록과 묘비의 시각이 같으면 기록이 이긴다', () => {
  const m = mergeLogState(state([], [tomb('A', 'volume:v1', 30)]), state([vol('B', 'v1', 30)]));
  assert.deepEqual(live(m), ['B']);
});

test('같은 id: 더 늦은 updatedAt이 이기고 동률은 정규 JSON이 큰 쪽', () => {
  const older = vol('A', 'v1', 10, { currentPage: 1 });
  const newer = vol('A', 'v1', 11, { currentPage: 2 });
  assert.equal(mergeStates(state([older]), state([newer])).logs[0].currentPage, 2);
  const x = vol('A', 'v1', 10, { currentPage: 1 });
  const y = vol('A', 'v1', 10, { currentPage: 2 });
  const winner = canonicalJson(x) > canonicalJson(y) ? x : y;
  assert.deepEqual(mergeStates(state([x]), state([y])).logs[0], winner);
  assert.deepEqual(mergeStates(state([y]), state([x])).logs[0], winner);
});

test('targetKey를 알 수 없는 기록과 targetKey 없는 묘비는 버리고 개수를 돌려준다', () => {
  const bad = vol('X', null, 10);
  const m = mergeStates(state([bad, vol('A', 'v1', 5), { id: 'junk' }], [{ id: 'T', deletedAt: iso(1) }, tomb('U', 'volume:v9', 2)]));
  assert.deepEqual(live(m), ['A']);
  assert.deepEqual(dead(m), { U: null });
  assert.equal(m.dropped, 3);
});

test('정규 JSON: 키 정렬, 공백 없음', () => {
  assert.equal(canonicalJson({ b: 1, a: [true, null, 'x'] }), '{"a":[true,null,"x"],"b":1}');
});

test('pruneTombstones: 180일이 지난 묘비만 뺀다 (now는 인자로)', () => {
  const now = Date.parse(iso(0)) + TOMBSTONE_KEEP_MS;
  const kept = pruneTombstones([tomb('old', 'volume:a', -1), tomb('edge', 'volume:b', 0), tomb('new', 'volume:c', 5)], now);
  assert.deepEqual(kept.map((t) => t.id), ['edge', 'new']);
});

test('시각 규칙: max(지금, 서버 written_at+1ms, 직전 값+1ms)', () => {
  const now = Date.parse('2026-01-01T00:00:00.000Z');
  assert.equal(computeStamp(now, null, null), '2026-01-01T00:00:00.000Z');
  assert.equal(computeStamp(now, '2026-01-01T00:00:05.000Z', null), '2026-01-01T00:00:05.001Z');
  assert.equal(computeStamp(now, '2026-01-01T00:00:05.000Z', '2026-01-01T00:00:09.000Z'), '2026-01-01T00:00:09.001Z');
  assert.equal(computeStamp(now, '2025-12-31T00:00:00.000Z', '2025-12-31T00:00:00.000Z'), '2026-01-01T00:00:00.000Z');
});

// ---- 속성 기반: 시드 고정 난수로 같은 대상에 여러 기기가 기록·수정·삭제 ----
function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
// 한 id는 늘 같은 대상을 가리킨다 (id는 기록을 만들 때 정해지고, 대상은 바뀌지 않는다)
const TARGET_OF = { a: 'v1', b: 'v1', c: 'v2', d: 'v2', e: 'v3', f: 'v3' };
function randomState(rand, ids) {
  const logs = [];
  const tombstones = [];
  const n = 1 + Math.floor(rand() * 5);
  for (let i = 0; i < n; i++) {
    const id = ids[Math.floor(rand() * ids.length)];
    const target = TARGET_OF[id] ?? 'v1';
    const t = Math.floor(rand() * 6) * 10; // 시각이 자주 겹치게 해서 동률 규칙도 시험
    const kind = rand();
    if (kind < 0.7) logs.push(vol(id, target, t, { currentPage: Math.floor(rand() * 3), liked: rand() < 0.5 }));
    else tombstones.push(tomb(id, `volume:${target}`, t));
  }
  return state(logs, tombstones);
}

test('병합은 교환·결합·멱등 (속성 테스트, 시드 고정 2000회)', () => {
  const ids = ['a', 'b', 'c', 'd', 'e', 'f'];
  const rand = rng(20261103);
  for (let i = 0; i < 2000; i++) {
    const x = randomState(rand, ids);
    const y = randomState(rand, ids);
    const z = randomState(rand, ids);
    const sx = JSON.stringify;
    const strip = (m) => ({ logs: m.logs, tombstones: m.tombstones });
    // 교환
    assert.equal(sx(strip(mergeLogState(x, y))), sx(strip(mergeLogState(y, x))), `교환 #${i}`);
    // 결합
    assert.equal(
      sx(strip(mergeLogState(strip(mergeLogState(x, y)), z))),
      sx(strip(mergeLogState(x, strip(mergeLogState(y, z))))),
      `결합 #${i}`,
    );
    assert.equal(sx(strip(mergeLogState(strip(mergeLogState(x, y)), z))), sx(strip(mergeStates(x, y, z))), `n항 #${i}`);
    // 멱등
    const m = strip(mergeLogState(x, y));
    assert.equal(sx(strip(mergeLogState(m, m))), sx(m), `멱등 #${i}`);
    assert.equal(sx(strip(mergeLogState(m, x))), sx(m), `흡수 #${i}`);
    assert.ok(sameState(m, mergeLogState(m, y)));
  }
});

test('대상마다 살아 있는 기록은 많아야 하나', () => {
  const ids = ['a', 'b', 'c', 'd', 'e', 'f'];
  const rand = rng(7);
  for (let i = 0; i < 500; i++) {
    const m = mergeLogState(randomState(rand, ids), randomState(rand, ids));
    const keys = m.logs.map((r) => `volume:${r.volumeId}`);
    assert.equal(new Set(keys).size, keys.length);
    for (const r of m.logs) assert.ok(!m.tombstones.some((t) => t.id === r.id));
  }
});
