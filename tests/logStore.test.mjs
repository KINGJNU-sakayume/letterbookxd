import './setup.mjs';
import test, { beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import {
  useLogStore, useBookStore, getDb, resetDbForTests, setBundledCatalogLoader, LOG_ID_PATTERN,
  decideSetCompletion, decideSeriesCompletion,
} from '../.test-dist/app.js';

// Synthetic data only.
const T = '2026-01-01T00:00:00.000Z';
const work = (id, series_id = null, series_order = null) => ({
  id, title: `가상 작품 ${id}`, author: '가상 작가', original_excerpt: '', representative_cover_url: null,
  series_id, series_order, created_at: T,
});
const CATALOG = {
  version: 1,
  works: [work('w1', 's1', 1), work('w2', 's1', 2), work('w3')],
  editions: [], series: [{ id: 's1', title: '가상 시리즈', author: '가상 작가', created_at: T }], authors: [], flowcharts: [],
};
// w1: 두 권짜리 판본 set1 (v1, v2), w2: 한 권짜리 set2 (v3), w3: 한 권짜리 set3 (v4)
const VOLUMES = [
  { id: 'v1', editionSetId: 'set1', volumeNumber: 1, title: '1' },
  { id: 'v2', editionSetId: 'set1', volumeNumber: 2, title: '2' },
  { id: 'v3', editionSetId: 'set2', volumeNumber: 1, title: '1' },
  { id: 'v4', editionSetId: 'set3', volumeNumber: 1, title: '1' },
];
const WORK_OF = { set1: 'w1', set2: 'w2', set3: 'w3' };

const store = () => useLogStore.getState();
const vol = (volumeId, readingState, extra = {}) => {
  const editionSetId = VOLUMES.find((v) => v.id === volumeId).editionSetId;
  return store().upsertVolumeLog({
    volumeId, editionSetId, workId: WORK_OF[editionSetId], logType: 'volume',
    readingState, currentPage: null, liked: false, rating: null, ...extra,
  });
};
const stored = () => getDb().logs.toArray();

beforeEach(async () => {
  await resetDbForTests();
  setBundledCatalogLoader(async () => structuredClone(CATALOG));
  useBookStore.setState({ works: [], editionSets: [], volumes: VOLUMES });
  useLogStore.setState({ volumeLogs: [], setCompletionLogs: [], seriesCompletionLogs: [], hasLoaded: false });
  await store().loadLogs();
});

test('연쇄 판정 순수 함수', () => {
  const logs = [{ volumeId: 'a', readingState: 'completed' }, { volumeId: 'b', readingState: 'reading' }];
  assert.equal(decideSetCompletion([], logs, false), 'none');
  assert.equal(decideSetCompletion(['a'], logs, false), 'create');
  assert.equal(decideSetCompletion(['a'], logs, true), 'none');
  assert.equal(decideSetCompletion(['a', 'b'], logs, true), 'delete');
  assert.equal(decideSeriesCompletion(['w1', 'w2'], [{ workId: 'w1' }], false), 'none');
  assert.equal(decideSeriesCompletion(['w1', 'w2'], [{ workId: 'w1' }, { workId: 'w2' }], false), 'create');
  assert.equal(decideSeriesCompletion(['w1', 'w2'], [{ workId: 'w1' }], true), 'delete');
});

test('권 기록: 만들고 고치면 id·createdAt은 그대로, updatedAt은 바뀜, IndexedDB에 저장', async () => {
  await vol('v4', 'reading', { currentPage: 10 });
  const first = store().getVolumeLog('v4');
  assert.match(first.id, LOG_ID_PATTERN);
  assert.match(first.id, /^[0-9a-f-]{36}$/);
  assert.equal(first.readingState, 'reading');
  assert.equal(first.watched, false);

  await new Promise((r) => setTimeout(r, 5));
  await store().updateReadingProgress('v4', 42);
  assert.equal(store().getVolumeLog('v4').currentPage, 42);

  await vol('v4', 'reading', { currentPage: 50, rating: null });
  const second = store().getVolumeLog('v4');
  assert.equal(second.id, first.id);
  assert.equal(second.createdAt, first.createdAt);
  assert.ok(second.updatedAt > first.updatedAt);
  assert.equal(store().volumeLogs.length, 1);

  // 새로 불러와도 같다
  useLogStore.setState({ volumeLogs: [] });
  await store().loadLogs();
  assert.equal(store().getVolumeLog('v4').currentPage, 50);
  assert.equal((await stored()).length, 1);
});

test('세트 완독: 모든 권을 완독하면 자동 생성, 한 권이라도 되돌리면 삭제', async () => {
  await vol('v1', 'completed');
  assert.equal(store().getSetCompletionLog('set1'), undefined);
  await vol('v2', 'completed');
  const set = store().getSetCompletionLog('set1');
  assert.ok(set);
  assert.equal(set.autoGenerated, true);
  assert.equal(set.workId, 'w1');
  assert.match(set.id, LOG_ID_PATTERN);

  await store().upsertSetCompletionLog({ editionSetId: 'set1', workId: 'w1', liked: true, rating: 4.5 });
  const rec = (await stored()).find((r) => r.id === set.id);
  assert.equal(rec.rating, 4.5);
  assert.equal(rec.liked, true);
  assert.equal(rec.createdAt, set.createdAt);

  await vol('v2', 'reading');
  assert.equal(store().getSetCompletionLog('set1'), undefined);
  assert.equal((await stored()).filter((r) => r.logType === 'set_completion').length, 0);
});

test('시리즈 완독: 시리즈의 모든 작품 세트 완독 시 생성, 하나가 풀리면 삭제', async () => {
  await vol('v1', 'completed');
  await vol('v2', 'completed');
  assert.equal(store().getSeriesCompletionLog('s1'), undefined);
  await vol('v3', 'completed');
  const series = store().getSeriesCompletionLog('s1');
  assert.ok(series);
  assert.equal(series.autoGenerated, true);

  await store().upsertSeriesCompletionLog({ seriesId: 's1', liked: true, rating: 5 });
  assert.equal(store().getSeriesCompletionLog('s1').id, series.id);
  assert.equal(store().getSeriesCompletionLog('s1').autoGenerated, true);
  assert.equal(store().getSeriesCompletionLog('s1').rating, 5);

  // 시리즈가 아닌 작품은 시리즈 기록을 만들지 않는다
  await vol('v4', 'completed');
  assert.equal(store().seriesCompletionLogs.length, 1);

  await vol('v3', 'unread');
  assert.equal(store().getSeriesCompletionLog('s1'), undefined);
  assert.equal((await stored()).filter((r) => r.logType === 'series_completion').length, 0);
});

test('사용자가 직접 남긴 시리즈 평가는 autoGenerated=false', async () => {
  await store().upsertSeriesCompletionLog({ seriesId: 's1', liked: false, rating: 3 });
  const log = store().getSeriesCompletionLog('s1');
  assert.equal(log.autoGenerated, false);
  assert.match(log.id, LOG_ID_PATTERN);
});

test('deleteLogById: 권 기록을 지우면 세트·시리즈 완독도 지운다', async () => {
  for (const v of ['v1', 'v2', 'v3', 'v4']) await vol(v, 'completed');
  assert.equal(store().setCompletionLogs.length, 3);
  assert.equal(store().seriesCompletionLogs.length, 1);

  assert.equal(await store().deleteLogById(store().getVolumeLog('v1').id), true);
  assert.equal(store().getVolumeLog('v1'), undefined);
  assert.equal(store().getSetCompletionLog('set1'), undefined);
  assert.ok(store().getSetCompletionLog('set2'));
  assert.ok(store().getSetCompletionLog('set3'));
  assert.equal(store().seriesCompletionLogs.length, 0);
});

test('deleteLogById: 세트 완독을 지우면 시리즈 완독도, 시리즈 완독은 혼자 지운다', async () => {
  for (const v of ['v1', 'v2', 'v3']) await vol(v, 'completed');
  await store().deleteLogById(store().getSetCompletionLog('set2').id);
  assert.equal(store().getSetCompletionLog('set2'), undefined);
  assert.ok(store().getSetCompletionLog('set1'));
  assert.equal(store().seriesCompletionLogs.length, 0);
  assert.equal(store().volumeLogs.length, 3);

  await store().upsertSeriesCompletionLog({ seriesId: 's1', liked: false, rating: 2 });
  await store().deleteLogById(store().getSeriesCompletionLog('s1').id);
  assert.equal(store().seriesCompletionLogs.length, 0);
  assert.equal(store().setCompletionLogs.length, 1);
});

test('updateLogMetadata: 완독일(createdAt)·별점·인생책을 바꾼다', async () => {
  await vol('v4', 'completed');
  const set = store().getSetCompletionLog('set3');
  const day = '2025-06-01T03:00:00.000Z';
  assert.equal(await store().updateLogMetadata(set.id, { rating: 3, liked: true, createdAt: day }), true);
  const after = store().getSetCompletionLog('set3');
  assert.equal(after.createdAt, day);
  assert.equal(after.rating, 3);
  assert.equal(after.liked, true);
  assert.equal(await store().updateLogMetadata('missing-id', { rating: 1, liked: false, createdAt: day }), false);
});

test('deleteLogsByWorkId와 applyImport', async () => {
  await vol('v1', 'completed');
  await vol('v2', 'completed');
  await vol('v4', 'reading');
  assert.equal(await store().deleteLogsByWorkId('w1'), true);
  assert.equal(store().volumeLogs.length, 1);
  assert.equal(store().setCompletionLogs.length, 0);

  const existing = store().getVolumeLog('v4');
  const rec = {
    id: 'imported_1', logType: 'set_completion', volumeId: null, editionSetId: 'set2', workId: 'w2', seriesId: null,
    readingState: null, currentPage: null, liked: false, rating: 4, autoGenerated: true, createdAt: T, updatedAt: T, extra: 'drop me',
  };
  assert.equal(await store().applyImport([rec], [existing.id]), true);
  assert.equal(store().getVolumeLog('v4'), undefined);
  assert.equal(store().getSetCompletionLog('set2').rating, 4);
  const raw = (await stored()).find((r) => r.id === 'imported_1');
  assert.equal(raw.extra, undefined);
});
