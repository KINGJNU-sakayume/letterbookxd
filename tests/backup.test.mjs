import './setup.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {
  buildBackup, parseBackup, parseCsv, parseImportFile, parseSupabaseLogsCsv, pgTimestampToIso, planImport, resolvePlan,
  emptyCatalog,
} from '../.test-dist/app.js';

// Synthetic data only.
const T = '2026-01-01T00:00:00.000Z';
const rec = (patch = {}) => ({
  id: '00000000-0000-4000-8000-000000000001', logType: 'volume', volumeId: 'v1', editionSetId: 'set1', workId: 'w1',
  seriesId: null, readingState: 'completed', currentPage: null, liked: false, rating: 4, autoGenerated: false,
  createdAt: T, updatedAt: T, ...patch,
});

test('백업 왕복: 형식, 정렬, 카탈로그 편집본', () => {
  const override = { catalog: emptyCatalog(), baseHash: 'abc', updatedAt: T };
  const b = buildBackup([rec({ id: 'b', createdAt: '2026-02-01T00:00:00.000Z' }), rec({ id: 'a', volumeId: 'v2' })], override, new Date(T));
  assert.equal(b.app, 'letterbookxd');
  assert.equal(b.version, 1);
  assert.equal(b.exportedAt, T);
  assert.deepEqual(b.logs.map((l) => l.id), ['a', 'b']);
  const parsed = parseBackup(JSON.stringify(b));
  assert.equal(parsed.ok, true);
  assert.equal(parsed.source.kind, 'backup');
  assert.deepEqual(parsed.source.logs, b.logs);
  assert.deepEqual(parsed.source.catalogOverride, override);
  assert.equal(parsed.source.exportedAt, T);
  assert.equal(buildBackup([], null).catalogOverrides, undefined);
});

test('백업 검증: 다른 앱·버전·깨진 JSON은 거부, 잘못된 기록은 건너뜀', () => {
  assert.equal(parseBackup('{').ok, false);
  assert.equal(parseBackup(JSON.stringify({ app: 'other', version: 1, logs: [] })).ok, false);
  assert.equal(parseBackup(JSON.stringify({ app: 'letterbookxd', version: 2, logs: [] })).ok, false);
  assert.equal(parseBackup(JSON.stringify({ app: 'letterbookxd', version: 1 })).ok, false);
  const r = parseBackup(JSON.stringify({
    app: 'letterbookxd', version: 1, exportedAt: T,
    logs: [rec(), rec({ id: 'bad id!' }), rec({ id: 'x', readingState: 'maybe' }), rec({ id: 'y', rating: 9 }), rec({ id: 'z', createdAt: 'nope' })],
  }));
  assert.equal(r.ok, true);
  assert.equal(r.source.logs.length, 1);
  assert.equal(r.source.warnings.length, 4);
});

test('불러오기 계획: 새 기록, 동일, 같은 id 충돌, 같은 대상 충돌', () => {
  const existing = [rec(), rec({ id: 'set-a', logType: 'set_completion', volumeId: null, readingState: null })];
  const incoming = [
    rec(), // 동일
    rec({ id: 'set-a', logType: 'set_completion', volumeId: null, readingState: null, rating: 2 }), // 같은 id, 내용 다름
    rec({ id: 'other-id', volumeId: 'v1', rating: 1 }), // 다른 id로 같은 권 -> 하지만 v1은 이미 위 rec()이 차지
    rec({ id: 'new-1', volumeId: 'v9' }), // 새 기록
    rec({ id: 'new-1-dup', volumeId: 'v9' }), // 파일 안 중복은 무시
  ];
  const plan = planImport(existing, incoming);
  assert.deepEqual(plan.added.map((r) => r.id), ['new-1']);
  assert.deepEqual(plan.unchanged.map((r) => r.id), [existing[0].id]);
  // 'other-id'는 같은 대상(v1)이 파일 안에서 이미 처리되어 건너뛴다
  assert.deepEqual(plan.conflicts.map((c) => [c.incoming.id, c.reason]), [['set-a', 'same-id']]);

  const plan2 = planImport(existing, [rec({ id: 'other-id', rating: 1 })]);
  assert.deepEqual(plan2.conflicts.map((c) => [c.existing.id, c.reason]), [[existing[0].id, 'same-target']]);

  assert.deepEqual(resolvePlan(plan2, 'skip'), { put: [], deleteIds: [] });
  const over = resolvePlan(plan2, 'overwrite');
  assert.deepEqual(over.put.map((r) => r.id), ['other-id']);
  assert.deepEqual(over.deleteIds, [existing[0].id]);
});

test('CSV 파서: 따옴표, 이스케이프, 줄바꿈, BOM', () => {
  assert.deepEqual(parseCsv('﻿a,b\r\n"x, y","say ""hi"""\n"multi\nline",\n'), [['a', 'b'], ['x, y', 'say "hi"'], ['multi\nline', '']]);
  assert.equal(pgTimestampToIso('2026-03-04 05:06:07.123+00'), '2026-03-04T05:06:07.123Z');
  assert.equal(pgTimestampToIso('2026-03-04 14:06:07+09'), '2026-03-04T05:06:07.000Z');
  assert.equal(pgTimestampToIso('2026-03-04T05:06:07.5+0000'), '2026-03-04T05:06:07.500Z');
  assert.equal(pgTimestampToIso(''), null);
  assert.equal(pgTimestampToIso('garbage'), null);
});

const CSV = [
  'id,user_id,volume_id,edition_set_id,work_id,series_id,log_type,watched,reading_state,current_page,liked,rating,auto_generated,created_at,updated_at',
  '11111111-1111-4111-8111-111111111111,u-synthetic,vol-1,set-1,work-1,,volume,true,completed,,false,4.5,false,2025-05-01 10:00:00+00,2025-05-02 10:00:00+00',
  '22222222-2222-4222-8222-222222222222,u-synthetic,vol-2,set-1,work-1,,volume,false,,120,false,,false,2025-05-01 10:00:00+00,',
  '33333333-3333-4333-8333-333333333333,u-synthetic,,set-1,work-1,,set_completion,false,,,true,5,,2025-05-03 10:00:00+00,2025-05-03 10:00:00+00',
  '44444444-4444-4444-8444-444444444444,u-synthetic,,,,series-1,series_completion,false,,,false,,true,2025-05-04 10:00:00+00,2025-05-04 10:00:00+00',
  '55555555-5555-4555-8555-555555555555,u-synthetic,,,,,series_completion,false,,,false,,true,2025-05-04 10:00:00+00,',
].join('\n');

test('Supabase logs CSV 변환', () => {
  const r = parseSupabaseLogsCsv(CSV);
  assert.equal(r.ok, true);
  const logs = r.source.logs;
  assert.equal(logs.length, 4);
  assert.equal(r.source.warnings.length, 1); // seriesId 없는 행
  const [a, b, c, d] = logs;
  assert.deepEqual(a, {
    id: '11111111-1111-4111-8111-111111111111', logType: 'volume', volumeId: 'vol-1', editionSetId: 'set-1', workId: 'work-1',
    seriesId: null, readingState: 'completed', currentPage: null, liked: false, rating: 4.5, autoGenerated: false,
    createdAt: '2025-05-01T10:00:00.000Z', updatedAt: '2025-05-02T10:00:00.000Z',
  });
  assert.equal(b.readingState, 'unread'); // reading_state 비고 watched=false
  assert.equal(b.currentPage, 120);
  assert.equal(b.updatedAt, b.createdAt); // updated_at이 비면 created_at
  assert.equal(c.autoGenerated, true); // 세트 완독의 빈 auto_generated는 true
  assert.equal(c.readingState, null);
  assert.equal(d.seriesId, 'series-1');

  assert.equal(parseSupabaseLogsCsv('a,b\n1,2').ok, false);
  const multi = parseSupabaseLogsCsv(CSV + '\n66666666-6666-4666-8666-666666666666,u-other,,,,series-2,series_completion,false,,,false,,true,2025-05-04 10:00:00+00,');
  assert.ok(multi.source.warnings.some((w) => w.includes('2명')));
});

test('parseImportFile: 내용으로 JSON·CSV를 고른다', () => {
  assert.equal(parseImportFile(CSV).source.kind, 'supabase-csv');
  assert.equal(parseImportFile('﻿  ' + JSON.stringify(buildBackup([rec()], null))).source.kind, 'backup');
});
