import './setup.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {
  buildBackup, parseBackup, parseImportFile, planImport, resolvePlan,
  emptyCatalog,
} from '../.test-dist/app.js';

// Synthetic data only.
const T = '2026-01-01T00:00:00.000Z';
const rec = (patch = {}) => ({
  id: '00000000-0000-4000-8000-000000000001', logType: 'volume', volumeId: 'v1', editionSetId: 'set1', workId: 'w1',
  seriesId: null, readingState: 'completed', currentPage: null, liked: false, rating: 4, autoGenerated: false,
  createdAt: T, updatedAt: T, ...patch,
});

test('백업 왕복: 형식, 정렬, 카탈로그 편집본', () => {
  const override = { catalog: emptyCatalog(), baseHash: 'abc', updatedAt: T };
  const b = buildBackup([rec({ id: 'b', createdAt: '2026-02-01T00:00:00.000Z' }), rec({ id: 'a', volumeId: 'v2' })], override, new Date(T));
  assert.equal(b.app, 'letterbookxd');
  assert.equal(b.version, 1);
  assert.equal(b.exportedAt, T);
  assert.deepEqual(b.logs.map((l) => l.id), ['a', 'b']);
  const parsed = parseBackup(JSON.stringify(b));
  assert.equal(parsed.ok, true);
  assert.equal(parsed.source.kind, 'backup');
  assert.deepEqual(parsed.source.logs, b.logs);
  assert.deepEqual(parsed.source.catalogOverride, override);
  assert.equal(parsed.source.exportedAt, T);
  assert.equal(buildBackup([], null).catalogOverrides, undefined);
});

test('백업 검증: 다른 앱·버전·깨진 JSON은 거부, 잘못된 기록은 건너뜀', () => {
  assert.equal(parseBackup('{').ok, false);
  assert.equal(parseBackup(JSON.stringify({ app: 'other', version: 1, logs: [] })).ok, false);
  assert.equal(parseBackup(JSON.stringify({ app: 'letterbookxd', version: 2, logs: [] })).ok, false);
  assert.equal(parseBackup(JSON.stringify({ app: 'letterbookxd', version: 1 })).ok, false);
  const r = parseBackup(JSON.stringify({
    app: 'letterbookxd', version: 1, exportedAt: T,
    logs: [rec(), rec({ id: 'bad id!' }), rec({ id: 'x', readingState: 'maybe' }), rec({ id: 'y', rating: 9 }), rec({ id: 'z', createdAt: 'nope' })],
  }));
  assert.equal(r.ok, true);
  assert.equal(r.source.logs.length, 1);
  assert.equal(r.source.warnings.length, 4);
});

test('불러오기 계획: 새 기록, 동일, 같은 id 충돌, 같은 대상 충돌', () => {
  const existing = [rec(), rec({ id: 'set-a', logType: 'set_completion', volumeId: null, readingState: null })];
  const incoming = [
    rec(), // 동일
    rec({ id: 'set-a', logType: 'set_completion', volumeId: null, readingState: null, rating: 2 }), // 같은 id, 내용 다름
    rec({ id: 'other-id', volumeId: 'v1', rating: 1 }), // 다른 id로 같은 권 -> 하지만 v1은 이미 위 rec()이 차지
    rec({ id: 'new-1', volumeId: 'v9' }), // 새 기록
    rec({ id: 'new-1-dup', volumeId: 'v9' }), // 파일 안 중복은 무시
  ];
  const plan = planImport(existing, incoming);
  assert.deepEqual(plan.added.map((r) => r.id), ['new-1']);
  assert.deepEqual(plan.unchanged.map((r) => r.id), [existing[0].id]);
  // 'other-id'는 같은 대상(v1)이 파일 안에서 이미 처리되어 건너뛴다
  assert.deepEqual(plan.conflicts.map((c) => [c.incoming.id, c.reason]), [['set-a', 'same-id']]);

  const plan2 = planImport(existing, [rec({ id: 'other-id', rating: 1 })]);
  assert.deepEqual(plan2.conflicts.map((c) => [c.existing.id, c.reason]), [[existing[0].id, 'same-target']]);

  assert.deepEqual(resolvePlan(plan2, 'skip'), { put: [], deleteIds: [] });
  const over = resolvePlan(plan2, 'overwrite');
  assert.deepEqual(over.put.map((r) => r.id), ['other-id']);
  assert.deepEqual(over.deleteIds, [existing[0].id]);
});

test('parseImportFile: BOM·앞 공백을 허용하고 JSON이 아니면 거부', () => {
  assert.equal(parseImportFile('\uFEFF  ' + JSON.stringify(buildBackup([rec()], null))).source.kind, 'backup');
  assert.equal(parseImportFile('id,log_type\n1,volume').ok, false);
});
